/**
 * Dynamically localizes an Experience object for the active selected language
 */
export function getDistrictLabel(dist, language = "en") {
  if (!dist) return "";
  if (typeof dist === "string") {
    const found = DISTRICTS.find((d) => d.id === dist || d.name === dist);
    if (found) return getDistrictLabel(found, language);
    return dist;
  }
  if (dist.names && dist.names[language]) return dist.names[language];
  if (language === "ta" && dist.tamilName) return dist.tamilName;
  return dist.name || "";
}

